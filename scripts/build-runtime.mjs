#!/usr/bin/env node
// Assemble a self-contained runtime copy of this server into a target directory.
//
// The source of truth stays in this repository. The deployed runtime is a build
// artifact: it carries the server modules, the Koffi dependency, and the SDK DLL,
// so the MCP client can launch it without reading anything from the source tree.
//
// Usage:
//   node scripts/build-runtime.mjs [targetDir]
//
// Default target: <DSH workspace>/everything-mcp-runtime
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_DIR = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DEFAULT_TARGET = "C:\\Users\\Arukas\\Documents\\deepseek-harness\\default-workspace\\everything-mcp-runtime";

const SERVER_MODULES = ["server.mjs", "everything.mjs", "mcp-protocol.mjs"];
const VENDOR_DLL = path.join("vendor", "Everything3_x64.dll");

function fail(message) {
  console.error(`build-runtime: ${message}`);
  process.exit(1);
}

function sha256(filePath) {
  return createHash("sha256").update(readFileSync(filePath)).digest("hex");
}

function copyFile(from, to) {
  mkdirSync(path.dirname(to), { recursive: true });
  cpSync(from, to);
}

const targetDir = path.resolve(process.argv[2] ?? DEFAULT_TARGET);

if (targetDir === SOURCE_DIR) fail("target must differ from the source directory");
if (targetDir.startsWith(SOURCE_DIR + path.sep)) fail("target must not be inside the source directory");

for (const module of SERVER_MODULES) {
  if (!existsSync(path.join(SOURCE_DIR, module))) fail(`missing server module: ${module}`);
}
const dllPath = path.join(SOURCE_DIR, VENDOR_DLL);
if (!existsSync(dllPath)) fail(`missing SDK DLL: ${VENDOR_DLL} (see README for how to obtain it)`);
const koffiDir = path.join(SOURCE_DIR, "node_modules", "koffi");
if (!existsSync(koffiDir)) fail("missing node_modules/koffi; run npm install in the source tree first");

const sourcePackage = JSON.parse(readFileSync(path.join(SOURCE_DIR, "package.json"), "utf8"));

// Rebuild from scratch so a removed file never lingers in the deployed copy.
rmSync(targetDir, { recursive: true, force: true });
mkdirSync(targetDir, { recursive: true });

for (const module of SERVER_MODULES) {
  copyFile(path.join(SOURCE_DIR, module), path.join(targetDir, module));
}
copyFile(dllPath, path.join(targetDir, VENDOR_DLL));

// Koffi ships prebuilt native binaries per platform; copy the whole package so the
// runtime resolves them exactly as the source tree does.
cpSync(path.join(SOURCE_DIR, "node_modules"), path.join(targetDir, "node_modules"), { recursive: true });

// A runtime-only manifest: no test scripts, no publish metadata, no bin entry.
const runtimePackage = {
  name: `${sourcePackage.name}-runtime`,
  version: sourcePackage.version,
  private: true,
  type: "module",
  description: "Deployed runtime for everything-sdk3-mcp. Generated by scripts/build-runtime.mjs; do not edit.",
  dependencies: sourcePackage.dependencies,
  engines: sourcePackage.engines,
};
writeFileSync(path.join(targetDir, "package.json"), `${JSON.stringify(runtimePackage, null, 2)}\n`);

const buildInfo = {
  generatedAt: new Date().toISOString(),
  sourceDir: SOURCE_DIR,
  version: sourcePackage.version,
  files: Object.fromEntries(
    [...SERVER_MODULES, VENDOR_DLL].map((relative) => [relative, sha256(path.join(targetDir, relative))]),
  ),
};
writeFileSync(path.join(targetDir, "BUILD-INFO.json"), `${JSON.stringify(buildInfo, null, 2)}\n`);

const countFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).reduce((total, entry) => {
    const full = path.join(dir, entry.name);
    return total + (entry.isDirectory() ? countFiles(full) : statSync(full).isFile() ? 1 : 0);
  }, 0);

console.log(`build-runtime: wrote ${countFiles(targetDir)} files to ${targetDir}`);
console.log(`build-runtime: version ${sourcePackage.version}, DLL sha256 ${buildInfo.files[VENDOR_DLL].slice(0, 16)}…`);
